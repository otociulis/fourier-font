import { expect, test } from '@playwright/test';

test('font switching stops playback and the next performance uses the new glyph harmonics', async ({ page }) => {
    await page.addInitScript(() => {
        const start = AudioBufferSourceNode.prototype.start;
        AudioBufferSourceNode.prototype.start = function (when = 0, offset = 0, duration?: number) {
            const samples = this.buffer!.getChannelData(0);
            document.documentElement.dataset.audioSignature = JSON.stringify(Array.from(samples.slice(200, 220)));
            start.call(this, when, offset, duration);
        };
    });
    await page.goto('/');
    await expect(page.getByRole('img', { name: /reconstruction/ })).toBeVisible();
    await page.getByRole('textbox', { name: 'Text to render' }).fill('AAAAAAAAAAAAAAAAAAAA');
    await page.getByRole('tab', { name: 'Sound', exact: true }).click();
    const signatures = new Set<string>();
    for (const label of ['Dancing Script', 'Sacramento', 'Roboto Mono']) {
        await page.getByRole('textbox', { name: 'Font', exact: true }).click();
        await page.getByRole('option', { name: label, exact: true }).click();
        await expect(page.getByRole('status')).toHaveText('Sound idle');
        await expect(page.getByRole('textbox', { name: 'Font', exact: true })).toBeEnabled();
        await page.getByRole('button', { name: 'Play sound', exact: true }).click();
        await expect(page.getByRole('status')).toHaveText('Playing speech');
        signatures.add((await page.locator('html').getAttribute('data-audio-signature'))!);
    }
    expect(signatures.size).toBe(3);
    await page.getByRole('button', { name: 'Stop', exact: true }).click();
    await expect(page.getByRole('status')).toHaveText('Sound idle');
});

test('plays real glyph PCM in both modes, finishes, stops, and cancels on edits', async ({ page }) => {
    await page.addInitScript(() => {
        const start = AudioBufferSourceNode.prototype.start;
        AudioBufferSourceNode.prototype.start = function (when = 0, offset = 0, duration?: number) {
            const data = this.buffer?.getChannelData(0);
            const peak = data?.reduce((max, value) => Math.max(max, Math.abs(value)), 0) ?? 0;
            document.documentElement.dataset.audioPeak = String(peak);
            document.documentElement.dataset.audioStarts = String(Number(document.documentElement.dataset.audioStarts ?? 0) + 1);
            start.call(this, when, offset, duration);
        };
    });
    const errors: string[] = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto('/');
    await expect(page.getByRole('img', { name: /reconstruction/ })).toBeVisible();
    await page.getByRole('textbox', { name: 'Text to render' }).fill('Aa Bb');
    await page.getByRole('tab', { name: 'Sound', exact: true }).click();
    await expect(page.getByRole('radio', { name: 'Tone', exact: true })).toBeChecked();
    const letterDuration = page.getByRole('slider', { name: 'Letter duration', exact: true });
    await expect(letterDuration).toHaveAttribute('aria-valuenow', '140');
    await letterDuration.focus();
    await page.keyboard.press('Home');
    await expect(letterDuration).toHaveAttribute('aria-valuenow', '40');
    await page.keyboard.press('ArrowRight');
    await expect(letterDuration).toHaveAttribute('aria-valuenow', '50');
    const basePitch = page.getByRole('slider', { name: 'Base pitch', exact: true });
    await expect(basePitch).toHaveAttribute('aria-valuenow', '140');
    await basePitch.focus();
    await page.keyboard.press('ArrowRight');
    await expect(basePitch).toHaveAttribute('aria-valuenow', '141');
    const questionRise = page.getByRole('slider', { name: 'Question rise', exact: true });
    await expect(questionRise).toHaveAttribute('aria-valuenow', '4');
    await questionRise.focus();
    await page.keyboard.press('ArrowRight');
    await expect(questionRise).toHaveAttribute('aria-valuenow', '4.5');
    await expect(page.getByRole('slider', { name: 'Exclamation lift', exact: true })).toHaveAttribute('aria-valuenow', '4');
    await expect(page.getByRole('slider', { name: 'Exclamation fall', exact: true })).toHaveAttribute('aria-valuenow', '2');
    const spaceGlide = page.getByRole('slider', { name: 'Space glide', exact: true });
    await expect(spaceGlide).toHaveAttribute('aria-valuenow', '0');
    await spaceGlide.focus();
    await page.keyboard.press('Home');
    await expect(spaceGlide).toHaveAttribute('aria-valuenow', '0');
    const dotPause = page.getByRole('slider', { name: 'Dot pause', exact: true });
    await expect(dotPause).toHaveAttribute('aria-valuenow', '214');
    await dotPause.focus();
    await page.keyboard.press('Home');
    await expect(dotPause).toHaveAttribute('aria-valuenow', '25');
    await page.keyboard.press('End');
    await expect(dotPause).toHaveAttribute('aria-valuenow', '1000');
    const pause = page.getByRole('slider', { name: 'Minimum word pause' });
    await expect(pause).toHaveAttribute('aria-valuenow', '143');
    await pause.focus();
    await page.keyboard.press('End');
    await expect(pause).toHaveAttribute('aria-valuenow', '500');
    await page.keyboard.press('Home');
    await expect(pause).toHaveAttribute('aria-valuenow', '25');
    await page.keyboard.press('ArrowRight');
    await expect(pause).toHaveAttribute('aria-valuenow', '26');
    const glide = page.getByRole('slider', { name: 'Glide duration' });
    await expect(glide).toHaveAttribute('aria-valuenow', '29');
    await glide.focus();
    await page.keyboard.press('Home');
    await expect(glide).toHaveAttribute('aria-valuenow', '0');
    await page.keyboard.press('End');
    await expect(glide).toHaveAttribute('aria-valuenow', '100');
    await expect(page.getByText('100% (50 ms)', { exact: true })).toBeVisible();
    await letterDuration.focus();
    await page.keyboard.press('ArrowRight');
    await expect(page.getByText('100% (60 ms)', { exact: true })).toBeVisible();
    await page.keyboard.press('ArrowLeft');
    await page.getByRole('button', { name: 'Play sound' }).click();
    await expect(page.getByRole('status')).toHaveText('Playing speech');
    await expect.poll(() => page.evaluate(() => Number(document.documentElement.dataset.audioPeak))).toBeGreaterThan(0.001);
    await expect(page.getByRole('status')).toHaveText('Sound idle');
    expect(await page.evaluate(() => Number(document.documentElement.dataset.audioStarts))).toBe(4);
    await page.getByRole('textbox', { name: 'Performance mode' }).click();
    await page.getByRole('option', { name: 'Sing', exact: true }).click();
    await expect(basePitch).toHaveAttribute('aria-valuenow', '196');
    await expect(letterDuration).toHaveAttribute('aria-valuenow', '420');
    await expect(questionRise).toHaveCount(0);
    await page.getByRole('textbox', { name: 'Performance mode' }).click();
    await page.getByRole('option', { name: 'Speech', exact: true }).click();
    await expect(basePitch).toHaveAttribute('aria-valuenow', '141');
    await expect(letterDuration).toHaveAttribute('aria-valuenow', '50');
    await expect(questionRise).toHaveAttribute('aria-valuenow', '4.5');
    await page.getByRole('textbox', { name: 'Performance mode' }).click();
    await page.getByRole('option', { name: 'Sing', exact: true }).click();
    await expect(spaceGlide).toHaveAttribute('aria-valuenow', '29');
    await page.getByText('Chords', { exact: true }).click();
    await page.getByRole('button', { name: 'Play sound' }).click();
    await expect(page.getByRole('status')).toHaveText('Playing sing');
    await page.getByText('Tone', { exact: true }).click();
    await expect(page.getByRole('status')).toHaveText('Sound idle');
    await page.getByText('Chords', { exact: true }).click();
    await page.getByRole('button', { name: 'Play sound' }).click();
    await expect(page.getByRole('status')).toHaveText('Playing sing');
    await page.getByRole('button', { name: 'Stop', exact: true }).click();
    await expect(page.getByRole('status')).toHaveText('Sound idle');
    await page.getByRole('button', { name: 'Play sound' }).click();
    await expect(page.getByRole('status')).toHaveText('Playing sing');
    await page.getByRole('status').filter({ hasText: 'Sound idle' }).waitFor();
    await page.getByRole('button', { name: 'Play sound' }).click();
    await page.getByRole('tab', { name: 'Composition' }).click();
    await page.getByRole('textbox', { name: 'Text to render' }).fill('C');
    await page.getByRole('tab', { name: 'Sound', exact: true }).click();
    await expect(page.getByRole('status')).toHaveText('Sound idle');
    await expect(page.getByRole('button', { name: 'Stop', exact: true })).toBeDisabled();
    expect(errors).toEqual([]);
});

test('reports unsupported text and missing Web Audio, and disables zero harmonics', async ({ page }) => {
    await page.goto('/');
    await expect(page.getByRole('img', { name: /reconstruction/ })).toBeVisible();
    await page.getByRole('textbox', { name: 'Text to render' }).fill('@');
    await page.getByRole('tab', { name: 'Sound', exact: true }).click();
    await page.getByRole('button', { name: 'Play sound' }).click();
    await expect(page.getByRole('alert', { name: 'Sound unavailable' })).toContainText('Enter supported glyphs');
    await page.getByRole('tab', { name: 'Composition' }).click();
    await page.getByRole('textbox', { name: 'Text to render' }).fill('A');
    await page.evaluate(() => Object.defineProperty(window, 'AudioContext', { configurable: true, value: undefined }));
    await page.getByRole('tab', { name: 'Sound', exact: true }).click();
    await page.getByRole('button', { name: 'Play sound' }).click();
    await expect(page.getByRole('alert', { name: 'Sound unavailable' })).toContainText('does not support Web Audio');
    await page.getByRole('tab', { name: 'Reconstruction' }).click();
    await page.getByRole('textbox', { name: 'Harmonic limit' }).fill('0');
    await page.getByRole('tab', { name: 'Sound', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Play sound' })).toBeDisabled();
});
